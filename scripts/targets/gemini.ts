import { readFile, readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { json, type GeneratedFile } from '../lib/files.ts'
import { HOOK_BUNDLE_NAME } from '../../packages/hooks/src/bundle.ts'
import { stdioLaunch, type Shared } from '../lib/shared.ts'

/**
 * Gemini CLI extension at the repo root (plan P0-7, finding F2): `gemini extensions install <repo>` reads
 * `gemini-extension.json`, `GEMINI.md`, `hooks/hooks.json`, `commands/` and `skills/` from the root.
 */
export const GEMINI_MANIFEST = 'gemini-extension.json'
export const GEMINI_CONTEXT = 'GEMINI.md'
export const GEMINI_HOOKS = 'hooks/hooks.json'
export const COMMANDS_DIR = 'shared/commands'
export const CONTEXT_TEMPLATE = 'shared/context/GEMINI.md.tmpl'

const GENERATED_BY = 'GENERATED by scripts/build.ts'

/** The automatic-context switch, off by default (plan decision D1). */
export const AUTO_CONTEXT_SETTING = {
  name: 'RushDB automatic context',
  description:
    'off (default), recall, or recall+persist. recall adds earlier sessions at session start; recall+persist also stores finished turns in your RushDB project.',
  envVar: 'RUSHDB_AUTO_CONTEXT',
  sensitive: false
}

/** The root package sets the version of every non-npm manifest. */
export async function rootVersion(root: string): Promise<string> {
  const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')) as { version?: unknown }
  if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`package.json version must be an x.y.z version, got ${JSON.stringify(version)}`)
  }
  return version
}

/**
 * The stdio server with its env taken from the extension settings. Gemini substitutes `${VAR}` from the settings
 * and `${VAR:-default}` when one is unset; extensions do not inherit the shell environment otherwise.
 */
export function geminiManifest(shared: Shared, version: string) {
  const { mcp, listing } = shared
  const env: Record<string, string> = {}
  const settings: Array<{ name: string; description: string; envVar: string; sensitive: boolean }> = []
  for (const [envVar, spec] of Object.entries(mcp.stdio.env)) {
    env[envVar] = spec.default === undefined ? `\${${envVar}}` : `\${${envVar}:-${spec.default}}`
    settings.push({ name: settingName(envVar), description: spec.description, envVar, sensitive: spec.sensitive })
  }
  settings.push(AUTO_CONTEXT_SETTING)
  return {
    name: listing.name,
    version,
    description: listing.description,
    contextFileName: GEMINI_CONTEXT,
    mcpServers: { [mcp.serverName]: { ...stdioLaunch(mcp), env } },
    settings
  }
}

function settingName(envVar: string): string {
  const words = envVar.replace(/^RUSHDB_/, '').split('_')
  return `RushDB ${words.map((word) => (word === 'API' || word === 'URL' ? word : word.toLowerCase())).join(' ')}`
}

/**
 * Gemini hooks (timeouts in ms). Capture and end only write the local outbox and start a detached flush, because
 * Gemini does not wait for `SessionEnd`. Gemini fires `PreCompress` before every turn, so precompact never blocks
 * there either. Per-prompt recall on `BeforeAgent` stays out for now.
 */
export function geminiHooks() {
  const command = (name: string, run: string, timeout: number, description: string) => ({
    type: 'command',
    name,
    command: `node "\${extensionPath}\${/}hooks\${/}${HOOK_BUNDLE_NAME}" ${run} --host gemini`,
    timeout,
    description
  })
  return {
    hooks: {
      // No matcher: Gemini compares a SessionStart matcher to the source by plain equality, not as a regex, and
      // recall belongs on startup, resume and clear alike.
      SessionStart: [
        {
          hooks: [
            command(
              'rushdb-recall',
              'recall',
              10_000,
              'Recall earlier context from RushDB when automatic context is on'
            )
          ]
        }
      ],
      AfterAgent: [
        {
          hooks: [
            command('rushdb-capture', 'capture', 30_000, 'Queue the finished turn for RushDB (recall+persist only)')
          ]
        }
      ],
      PreCompress: [
        {
          hooks: [command('rushdb-precompact', 'precompact', 30_000, 'Send queued turns to RushDB before compression')]
        }
      ],
      SessionEnd: [
        { hooks: [command('rushdb-end', 'end', 2_000, 'Hand queued turns to a background flush and return')] }
      ]
    }
  }
}

/** Fills `{{key}}` placeholders; an unknown placeholder is an error, so a template typo fails the build. */
export function fillTemplate(template: string, values: Record<string, string>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
    if (!(key in values)) throw new Error(`${CONTEXT_TEMPLATE} has an unknown placeholder ${match}`)
    return values[key]!
  })
}

/**
 * Context text from the one shared template: `GEMINI.md` for Gemini and `rules/<name>.md` for Antigravity.
 * `credentials` names the host's own way to set the API key.
 */
export function renderContext(shared: Shared, template: string, credentials: string): string {
  const body = fillTemplate(template, {
    displayName: shared.listing.displayName,
    serverName: shared.mcp.serverName,
    skills: shared.skills.skills.map((skill) => `\`${skill}\``).join(', '),
    credentials
  })
  return `<!-- ${GENERATED_BY} from ${CONTEXT_TEMPLATE}; do not edit. -->\n\n${body}`
}

export async function readContextTemplate(root: string): Promise<string> {
  return readFile(join(root, CONTEXT_TEMPLATE), 'utf8')
}

/** `shared/commands/<name>.toml` → `commands/<extension>/<name>.toml`, which Gemini names `/<extension>:<name>`. */
export async function geminiCommands(root: string, extension: string): Promise<GeneratedFile[]> {
  const names = (await readdir(join(root, COMMANDS_DIR))).filter((name) => name.endsWith('.toml')).sort()
  if (names.length === 0) throw new Error(`${COMMANDS_DIR} has no .toml commands`)
  const files: GeneratedFile[] = []
  for (const name of names) {
    const source = await readFile(join(root, COMMANDS_DIR, name), 'utf8')
    for (const field of ['description', 'prompt']) {
      if (!new RegExp(`^${field} = `, 'm').test(source)) throw new Error(`${COMMANDS_DIR}/${name} has no ${field}`)
    }
    files.push({
      path: `commands/${extension}/${name}`,
      content: `# ${GENERATED_BY} from ${COMMANDS_DIR}/${name}; do not edit.\n${source}`
    })
  }
  return files
}

export async function geminiExtension(shared: Shared, root: string): Promise<GeneratedFile[]> {
  const credentials = `\`gemini extensions config ${shared.listing.name}\``
  return [
    { path: GEMINI_MANIFEST, content: json(geminiManifest(shared, await rootVersion(root))) },
    { path: GEMINI_CONTEXT, content: renderContext(shared, await readContextTemplate(root), credentials) },
    { path: GEMINI_HOOKS, content: json(geminiHooks()) },
    ...(await geminiCommands(root, shared.listing.name))
  ]
}
