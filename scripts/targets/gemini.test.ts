import { cp, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { loadShared, type Shared } from '../lib/shared.ts'
import { fillTemplate, geminiCommands, geminiExtension, geminiHooks, geminiManifest } from './gemini.ts'

const repoRoot = resolve(import.meta.dirname, '../..')
let shared: Shared

beforeEach(async () => {
  shared = await loadShared(repoRoot)
})

describe('gemini-extension.json', () => {
  it('names the extension rushdb, pins the stdio server and takes its env from settings', () => {
    const manifest = geminiManifest(shared, '0.1.0')
    expect(manifest).toMatchObject({ name: 'rushdb', version: '0.1.0', contextFileName: 'GEMINI.md' })
    expect(manifest.mcpServers.rushdb).toEqual({
      command: 'npx',
      args: ['-y', '@rushdb/mcp-server@3.4.1'],
      env: {
        RUSHDB_API_KEY: '${RUSHDB_API_KEY}',
        RUSHDB_API_URL: '${RUSHDB_API_URL:-https://api.rushdb.com/api/v1}'
      }
    })
  })

  it('declares the key as sensitive and the automatic-context switch, which defaults to off', () => {
    const settings = geminiManifest(shared, '0.1.0').settings
    expect(settings.map((setting) => [setting.envVar, setting.sensitive])).toEqual([
      ['RUSHDB_API_KEY', true],
      ['RUSHDB_API_URL', false],
      ['RUSHDB_AUTO_CONTEXT', false]
    ])
    expect(settings[2]!.description).toMatch(/^off \(default\)/)
  })
})

describe('hooks/hooks.json', () => {
  it('runs the bundle from the extension path for recall, capture, precompact and end', () => {
    const { hooks } = geminiHooks()
    expect(Object.keys(hooks)).toEqual(['SessionStart', 'AfterAgent', 'PreCompress', 'SessionEnd'])
    const commands = Object.values(hooks).flatMap((groups) => groups.flatMap((group) => group.hooks))
    expect(commands.map((hook) => hook.command)).toEqual(
      ['recall', 'capture', 'precompact', 'end'].map(
        (run) => `node "\${extensionPath}\${/}hooks\${/}rushdb-hooks.mjs" ${run} --host gemini`
      )
    )
    expect(hooks.SessionStart[0]).not.toHaveProperty('matcher')
    expect(hooks).not.toHaveProperty('BeforeAgent')
  })
})

describe('context and commands', () => {
  let root: string
  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'agent-plugins-gemini-'))
    await cp(join(repoRoot, 'shared'), join(root, 'shared'), { recursive: true })
    await cp(join(repoRoot, 'package.json'), join(root, 'package.json'))
  })
  afterEach(async () => {
    await rm(root, { recursive: true, force: true })
  })

  it('fails on an unknown template placeholder', () => {
    expect(() => fillTemplate('{{displayName}} {{typo}}', { displayName: 'RushDB' })).toThrow(
      /unknown placeholder \{\{typo\}\}/
    )
  })

  it('writes GEMINI.md with the Gemini way to set the key and every shipped skill', async () => {
    const files = await geminiExtension(shared, root)
    const context = files.find((file) => file.path === 'GEMINI.md')!.content as string
    expect(context).toMatch(/^<!-- GENERATED by scripts\/build\.ts/)
    expect(context).toContain('`gemini extensions config rushdb`')
    expect(context).toContain('the hooks store finished turns themselves')
    for (const skill of shared.skills.skills) expect(context).toContain(`\`${skill}\``)
    expect(context).not.toMatch(/\{\{/)
  })

  it('copies each command under commands/rushdb with a generated header', async () => {
    const files = await geminiCommands(root, 'rushdb')
    expect(files.map((file) => file.path)).toEqual([
      'commands/rushdb/ask.toml',
      'commands/rushdb/recall.toml',
      'commands/rushdb/remember.toml'
    ])
    for (const file of files) expect(file.content).toMatch(/^# GENERATED by scripts\/build\.ts[^\n]*\ndescription = /)
  })

  it('rejects a command without a prompt', async () => {
    await writeFile(join(root, 'shared/commands/broken.toml'), 'description = "x"\n')
    await expect(geminiCommands(root, 'rushdb')).rejects.toThrow(/broken\.toml has no prompt/)
  })
})
