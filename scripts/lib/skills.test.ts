import { mkdtemp, readFile, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { commitAndTag, createSkillsRepo, skillMarkdown } from './fixtures.ts'
import type { SkillsPin } from './shared.ts'
import {
  checkSkills,
  formatSkillsSource,
  parseSkillsSource,
  skillsFiles,
  syncSkills,
  validateSkillMarkdown
} from './skills.ts'

let work: string
let upstream: string
let root: string
let pin: SkillsPin

beforeEach(async () => {
  work = await mkdtemp(join(tmpdir(), 'agent-plugins-skills-'))
  upstream = join(work, 'skills')
  root = join(work, 'repo')
  pin = { repository: 'https://github.com/rush-db/skills.git', tag: 'v3.0.5', skills: ['rushdb-a', 'rushdb-b'] }
})

afterEach(async () => {
  await rm(work, { recursive: true, force: true })
})

async function upstreamWith(files: Record<string, string> = {}): Promise<string> {
  return createSkillsRepo(upstream, pin.tag, {
    'rushdb-a/SKILL.md': skillMarkdown('rushdb-a'),
    'rushdb-a/references/spec.md': '# spec\n',
    'rushdb-b/SKILL.md': skillMarkdown('rushdb-b'),
    'rushdb-left-out/SKILL.md': skillMarkdown('rushdb-left-out'),
    'README.md': '# skills\n',
    ...files
  })
}

describe('validateSkillMarkdown', () => {
  it('accepts front matter with a string description', () => {
    expect(validateSkillMarkdown('rushdb-a', skillMarkdown('rushdb-a'))).toEqual([])
  })

  it('rejects a missing block, a missing description and a mismatched name', () => {
    expect(validateSkillMarkdown('rushdb-a', '# no front matter\n')).toEqual([
      'rushdb-a/SKILL.md must begin with YAML front matter'
    ])
    expect(validateSkillMarkdown('rushdb-a', '---\nname: rushdb-b\ndescription: [1]\n---\n')).toEqual([
      'rushdb-a/SKILL.md front matter needs a string description',
      'rushdb-a/SKILL.md front matter name is rushdb-b'
    ])
  })

  it('rejects front matter that is not valid YAML', () => {
    const [error] = validateSkillMarkdown('rushdb-a', '---\ndescription: Covers the flow: discover\n---\n')
    expect(error).toMatch(/^rushdb-a\/SKILL.md front matter is not valid YAML/)
  })
})

describe('SKILLS_SOURCE', () => {
  it('round-trips', () => {
    const source = {
      repository: 'r',
      tag: 'v3.0.5',
      commit: 'abc',
      skills: ['rushdb-a', 'rushdb-b'],
      sha256: 'f00',
      pending: false
    }
    const text = formatSkillsSource(source)
    expect(text.startsWith('# Generated by scripts/sync-skills.ts')).toBe(true)
    expect(parseSkillsSource(text)).toEqual(source)
  })

  it('marks a pending tag', () => {
    const source = { repository: 'r', tag: 'v3.0.5', commit: 'abc', skills: ['rushdb-a'], sha256: 'f00', pending: true }
    const text = formatSkillsSource(source)
    expect(text).toContain('status: pending v3.0.5; synced from an untagged commit')
    expect(parseSkillsSource(text)).toEqual(source)
  })
})

describe('syncSkills', () => {
  it('copies only the pinned skills at the tag and records tag and commit', async () => {
    const commit = await upstreamWith()
    const source = await syncSkills(root, pin, upstream)
    expect(source).toMatchObject({ tag: 'v3.0.5', commit, repository: pin.repository })
    expect(await readFile(join(root, 'skills/rushdb-a/references/spec.md'), 'utf8')).toBe('# spec\n')
    await expect(readFile(join(root, 'skills/rushdb-left-out/SKILL.md'))).rejects.toThrow()
    await expect(readFile(join(root, 'skills/README.md'))).rejects.toThrow()
    expect(parseSkillsSource(await readFile(join(root, 'skills/SKILLS_SOURCE'), 'utf8'))).toEqual(source)
    expect(await checkSkills(root, pin)).toEqual([])
  })

  it('replaces skills that are no longer pinned', async () => {
    await upstreamWith()
    await syncSkills(root, pin, upstream)
    await syncSkills(root, { ...pin, skills: ['rushdb-b'] }, upstream)
    await expect(readFile(join(root, 'skills/rushdb-a/SKILL.md'))).rejects.toThrow()
  })

  it('leaves skills/ untouched when a pinned skill fails validation', async () => {
    await upstreamWith()
    await syncSkills(root, pin, upstream)
    const before = await readFile(join(root, 'skills/SKILLS_SOURCE'), 'utf8')

    await writeFile(join(upstream, 'rushdb-b/SKILL.md'), '---\nname: rushdb-b\n---\n')
    commitAndTag(upstream, 'v3.0.6')

    await expect(syncSkills(root, { ...pin, tag: 'v3.0.6' }, upstream)).rejects.toThrow(
      'rushdb-b/SKILL.md front matter needs a string description'
    )
    expect(await readFile(join(root, 'skills/SKILLS_SOURCE'), 'utf8')).toBe(before)
  })

  it('fails on a pinned skill missing at the tag', async () => {
    await upstreamWith()
    await expect(syncSkills(root, { ...pin, skills: ['rushdb-a', 'rushdb-missing'] }, upstream)).rejects.toThrow()
  })

  it('fails on a symlink inside a pinned skill', async () => {
    await upstreamWith()
    await symlink('SKILL.md', join(upstream, 'rushdb-a/link.md'))
    commitAndTag(upstream, 'v3.0.7')
    await expect(syncSkills(root, { ...pin, tag: 'v3.0.7' }, upstream)).rejects.toThrow('Symlink not allowed')
  })
})

describe('syncSkills with a pending tag', () => {
  it('syncs the pending commit, records it, and fails the check once the pin drops it', async () => {
    await upstreamWith()
    await writeFile(join(upstream, 'rushdb-a/SKILL.md'), skillMarkdown('rushdb-a', 'Fixed: quoted.'))
    const commit = commitAndTag(upstream, 'unreleased')
    const pending = { ...pin, tag: 'v3.0.9', pendingCommit: commit }

    const source = await syncSkills(root, pending, upstream)
    expect(source).toMatchObject({ tag: 'v3.0.9', commit, pending: true })
    expect(await readFile(join(root, 'skills/rushdb-a/SKILL.md'), 'utf8')).toContain('Fixed: quoted.')
    expect(await checkSkills(root, pending)).toEqual([])

    expect(await checkSkills(root, { ...pin, tag: 'v3.0.9' })).toEqual([
      'skills come from an untagged commit but shared/skills.json pins the released v3.0.9; run pnpm sync:skills'
    ])
  })

  it('fails the check when skills were synced from a released tag but a pending commit is pinned', async () => {
    await upstreamWith()
    await syncSkills(root, pin, upstream)
    expect(await checkSkills(root, { ...pin, pendingCommit: 'a'.repeat(40) })).toEqual([
      `skills are not synced from the pending commit ${'a'.repeat(40)}; run pnpm sync:skills`
    ])
  })
})

describe('checkSkills', () => {
  beforeEach(async () => {
    await upstreamWith()
    await syncSkills(root, pin, upstream)
  })

  it('fails when a synced skill is edited by hand', async () => {
    await writeFile(join(root, 'skills/rushdb-a/SKILL.md'), skillMarkdown('rushdb-a', 'Edited.'))
    expect(await checkSkills(root, pin)).toEqual([
      'skills/ differs from what pnpm sync:skills wrote; do not edit synced skills by hand'
    ])
  })

  it('fails when a file is added', async () => {
    await writeFile(join(root, 'skills/rushdb-a/extra.md'), 'x')
    expect(await checkSkills(root, pin)).toEqual([
      'skills/ differs from what pnpm sync:skills wrote; do not edit synced skills by hand'
    ])
  })

  it('fails when the pin moves without a resync', async () => {
    expect(await checkSkills(root, { ...pin, tag: 'v3.0.9' })).toEqual([
      'skills are synced from v3.0.5 but shared/skills.json pins v3.0.9; run pnpm sync:skills'
    ])
  })

  it('fails when skills/ was never synced', async () => {
    await rm(join(root, 'skills'), { recursive: true })
    expect(await checkSkills(root, pin)).toEqual(['skills/SKILLS_SOURCE is missing; run pnpm sync:skills'])
  })
})

describe('skillsFiles', () => {
  it('copies the synced skills under a prefix, without SKILLS_SOURCE', async () => {
    await upstreamWith()
    await syncSkills(root, pin, upstream)
    const files = await skillsFiles(root, 'plugins/claude/rushdb/skills')
    expect(files.map((file) => file.path)).toEqual([
      'plugins/claude/rushdb/skills/rushdb-a/SKILL.md',
      'plugins/claude/rushdb/skills/rushdb-a/references/spec.md',
      'plugins/claude/rushdb/skills/rushdb-b/SKILL.md'
    ])
  })
})
