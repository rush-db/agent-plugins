import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parse } from 'yaml'
import { listFiles, type GeneratedFile } from './files.ts'
import type { SkillsPin } from './shared.ts'

export const SKILLS_DIR = 'skills'
export const SKILLS_SOURCE = 'SKILLS_SOURCE'
/** Claude directory limit per file (plan finding F9). */
export const MAX_FILE_BYTES = 256 * 1024

export interface SkillsSource {
  repository: string
  tag: string
  commit: string
  skills: string[]
  sha256: string
}

/** Checks that SKILL.md opens with YAML front matter holding a string `name` and `description`. */
export function validateSkillMarkdown(skill: string, content: string): string[] {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(content)
  if (!match) return [`${skill}/SKILL.md must begin with YAML front matter`]
  let data: unknown
  try {
    data = parse(match[1])
  } catch (error) {
    return [`${skill}/SKILL.md front matter is not valid YAML: ${error instanceof Error ? error.message : error}`]
  }
  if (typeof data !== 'object' || data === null) return [`${skill}/SKILL.md front matter must be a mapping`]
  const errors: string[] = []
  const { name, description } = data as Record<string, unknown>
  if (typeof description !== 'string' || description.trim() === '') {
    errors.push(`${skill}/SKILL.md front matter needs a string description`)
  }
  if (name !== undefined && name !== skill) errors.push(`${skill}/SKILL.md front matter name is ${String(name)}`)
  return errors
}

/** Hash of a skills tree: every file path and its bytes, in path order, excluding SKILLS_SOURCE. */
export async function hashSkillsTree(dir: string): Promise<string> {
  const hash = createHash('sha256')
  for (const path of await listFiles(dir)) {
    if (path === SKILLS_SOURCE) continue
    hash
      .update(path)
      .update('\0')
      .update(await readFile(join(dir, path)))
      .update('\0')
  }
  return hash.digest('hex')
}

/** Validates the copied skills: names, front matter, file sizes and no symlinks. */
export async function validateSkillsTree(dir: string, skills: string[]): Promise<string[]> {
  const errors: string[] = []
  const files = await listFiles(dir)
  for (const skill of skills) {
    const content = await readFile(join(dir, skill, 'SKILL.md'), 'utf8').catch(() => undefined)
    if (content === undefined) errors.push(`${skill}/SKILL.md is missing`)
    else errors.push(...validateSkillMarkdown(skill, content))
  }
  for (const path of files) {
    if (path === SKILLS_SOURCE) continue
    if (!skills.includes(path.split('/')[0])) errors.push(`${path} is not part of a pinned skill`)
    const size = (await readFile(join(dir, path))).length
    if (size > MAX_FILE_BYTES) errors.push(`${path} is ${size} bytes; the limit is ${MAX_FILE_BYTES}`)
  }
  return errors
}

export function formatSkillsSource(source: SkillsSource): string {
  return [
    '# Generated by scripts/sync-skills.ts from shared/skills.json. Do not edit; run `pnpm sync:skills`.',
    `repository: ${source.repository}`,
    `tag: ${source.tag}`,
    `commit: ${source.commit}`,
    `skills: ${source.skills.join(', ')}`,
    `sha256: ${source.sha256}`,
    ''
  ].join('\n')
}

export function parseSkillsSource(text: string): SkillsSource {
  const fields = new Map<string, string>()
  for (const line of text.split('\n')) {
    if (line.startsWith('#') || line.trim() === '') continue
    const index = line.indexOf(': ')
    if (index > 0) fields.set(line.slice(0, index), line.slice(index + 2).trim())
  }
  const field = (key: string): string => {
    const value = fields.get(key)
    if (!value) throw new Error(`${SKILLS_SOURCE} has no ${key}`)
    return value
  }
  return {
    repository: field('repository'),
    tag: field('tag'),
    commit: field('commit'),
    skills: field('skills')
      .split(',')
      .map((skill) => skill.trim()),
    sha256: field('sha256')
  }
}

/**
 * Checks the committed `skills/` against the pin and the hash recorded at sync time,
 * so a hand edit or a pin change without a resync fails `build --check`.
 */
export async function checkSkills(root: string, pin: SkillsPin): Promise<string[]> {
  const dir = join(root, SKILLS_DIR)
  const text = await readFile(join(dir, SKILLS_SOURCE), 'utf8').catch(() => undefined)
  if (text === undefined) return [`${SKILLS_DIR}/${SKILLS_SOURCE} is missing; run pnpm sync:skills`]
  let source: SkillsSource
  try {
    source = parseSkillsSource(text)
  } catch (error) {
    return [error instanceof Error ? error.message : String(error)]
  }
  const errors: string[] = []
  if (source.tag !== pin.tag) errors.push(`skills are synced from ${source.tag} but shared/skills.json pins ${pin.tag}`)
  if (source.repository !== pin.repository) errors.push(`skills come from ${source.repository}, not ${pin.repository}`)
  if (source.skills.join(',') !== pin.skills.join(',')) {
    errors.push('the synced skill list differs from shared/skills.json')
  }
  try {
    errors.push(...(await validateSkillsTree(dir, pin.skills)).map((error) => `${SKILLS_DIR}/${error}`))
    if ((await hashSkillsTree(dir)) !== source.sha256) {
      errors.push(`${SKILLS_DIR}/ differs from what pnpm sync:skills wrote; do not edit synced skills by hand`)
    }
  } catch (error) {
    errors.push(error instanceof Error ? error.message : String(error))
  }
  return errors.map((error) => (error.includes('pnpm sync:skills') ? error : `${error}; run pnpm sync:skills`))
}

/** Copies of the synced skills under `prefix`, for platform folders that ship their own `skills/`. */
export async function skillsFiles(root: string, prefix: string): Promise<GeneratedFile[]> {
  const dir = join(root, SKILLS_DIR)
  const files: GeneratedFile[] = []
  for (const path of await listFiles(dir)) {
    if (path === SKILLS_SOURCE) continue
    files.push({ path: `${prefix}/${path}`, content: await readFile(join(dir, path)) })
  }
  return files
}

function git(args: string[], cwd?: string): string {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
}

/**
 * Copies the pinned skills from `repository` (a URL or a local path) at `pin.tag` into
 * `<root>/skills`, through `git archive` of a shallow fetch, and writes SKILLS_SOURCE.
 * Nothing in `skills/` changes unless every check passes.
 */
export async function syncSkills(root: string, pin: SkillsPin, repository = pin.repository): Promise<SkillsSource> {
  const work = await mkdtemp(join(tmpdir(), 'rushdb-skills-'))
  try {
    const bare = join(work, 'repo.git')
    git(['init', '--quiet', '--bare', bare])
    git(['fetch', '--quiet', '--depth', '1', repository, `refs/tags/${pin.tag}:refs/tags/${pin.tag}`], bare)
    const commit = git(['rev-parse', `${pin.tag}^{commit}`], bare)
    const archive = join(work, 'skills.tar')
    git(['archive', '--format=tar', `--output=${archive}`, pin.tag, ...pin.skills], bare)
    const extracted = join(work, 'out')
    await mkdir(extracted)
    execFileSync('tar', ['-xf', archive, '-C', extracted])

    const errors = await validateSkillsTree(extracted, pin.skills)
    if (errors.length > 0) throw new Error(`Skills at ${pin.tag} failed validation:\n${errors.join('\n')}`)

    const source: SkillsSource = {
      repository: pin.repository,
      tag: pin.tag,
      commit,
      skills: pin.skills,
      sha256: await hashSkillsTree(extracted)
    }
    await writeFile(join(extracted, SKILLS_SOURCE), formatSkillsSource(source))
    const target = join(root, SKILLS_DIR)
    await rm(target, { recursive: true, force: true })
    await cp(extracted, target, { recursive: true })
    return source
  } finally {
    await rm(work, { recursive: true, force: true })
  }
}
